// schemaInitAdvisoryKey is the fixed, project-specific advisory-lock key that
// serializes concurrent schema initializations on one database. The lock is
// transaction-scoped (pg_advisory_xact_lock), so it is released automatically
// at COMMIT/ROLLBACK.
const schemaInitAdvisoryKey int64 = 7881644658832750185 // 'magneti' little-endian

// ErrLegacySchema reports a legacy magnetico layout. This tool never migrates
// or alters such a database; conversion is the offline migrator's job.
var ErrLegacySchema = errors.New(
	"a legacy magnetico schema was detected; refusing to touch it " +
		"(no automatic migration exists; use the offline migrator)")

// SchemaStateError reports a refused schema state, naming the catalog objects
// (schema-qualified table/index names only — never data) that caused the
// refusal. It unwraps to ErrLegacySchema or ErrUnsupportedSchema.
type SchemaStateError struct {
	Err     error
	Details []string
}

func (e *SchemaStateError) Error() string {
	return e.Err.Error() + ": " + strings.Join(e.Details, "; ")
}

func (e *SchemaStateError) Unwrap() error { return e.Err }

// schemaStatements is the new-database DDL from postgresql-persistence-v2 §2,
// verbatim, plus the contract-mandated schema_version table and its initial
// row. Statements run inside one transaction on a re-verified fresh database.
var schemaStatements = []string{
	`CREATE SCHEMA IF NOT EXISTS magneticod`,

	`CREATE TABLE magneticod.torrents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info_hash BYTEA NOT NULL UNIQUE,
    name TEXT NOT NULL,
    total_size BIGINT NOT NULL CHECK (total_size > 0),
    discovered_on BIGINT NOT NULL CHECK (discovered_on > 0),
    file_count INTEGER NOT NULL CHECK (file_count > 0)
)`,

	`CREATE INDEX idx_torrents_total_size
    ON magneticod.torrents (total_size)`,

	`CREATE INDEX idx_torrents_discovered_on
    ON magneticod.torrents (discovered_on)`,

	`CREATE INDEX idx_torrents_name_gin_trgm
    ON magneticod.torrents USING GIN (name gin_trgm_ops)`,

	`CREATE TABLE magneticod.torrent_file_blobs (
    torrent_id INTEGER PRIMARY KEY
        REFERENCES magneticod.torrents(id) ON DELETE CASCADE,
    data BYTEA NOT NULL CHECK (octet_length(data) >= 2)
)`,

	`CREATE TABLE magneticod.schema_version (
    version INTEGER PRIMARY KEY,
    applied_on TIMESTAMPTZ NOT NULL DEFAULT now()
)`,

	`INSERT INTO magneticod.schema_version (version) VALUES ($1)`,
}

// expectedIndexes are the standalone (non-constraint) indexes verified beyond
// the tables. Constraint-backing indexes (pkey/unique) are excluded from the
// inventory, so the unknown-index guard only ever sees deliberately created
// indexes.
var expectedIndexes = []string{
	"idx_torrents_total_size",
	"idx_torrents_discovered_on",
	"idx_torrents_name_gin_trgm",
}

// magneticoObject is one non-sequence relation inside the magneticod schema.
// kind is the catalog relkind: r/p table, v view, m materialized view,
// f foreign table. Identity sequences are part of the expected state (owned
// by the IDENTITY columns) and are not inventoried.
type magneticoObject struct {
	name string
	kind string
}

// catalogInventory is the read-only picture of a database's magnetico-related
// state. Every query is SELECT-only; taking the inventory never writes
// anything, so a refusal leaves the database byte-identical.
type catalogInventory struct {
	schemas           []string // non-system schema names
	familyTables      []string // qualified `schema.table` for torrents/files/torrent_file_blobs/schema_version
	magneticodObjects []magneticoObject
	partitioned       []string // qualified names of partitioned tables among the family
	indexes           []string // index names inside magneticod
	torrentCols       []string // columns of magneticod.torrents (nil if absent)
	versionRows       []int64  // rows of magneticod.schema_version (nil if table absent)
	trgm              bool     // pg_trgm installed
}

type inventoryState int

const (
	stateFresh inventoryState = iota
	stateOK
	stateLegacy
	stateUnsupported
)

// hasFamilyTable reports whether tableName exists outside the magneticod
// schema (e.g. a legacy layout in public).
func (inv *catalogInventory) hasFamilyTableAnywhere(tableName string) bool {
	for _, qt := range inv.familyTables {
		if strings.HasSuffix(qt, "."+tableName) {
			return true
		}
	}
	return false
}

func (inv *catalogInventory) classify() (inventoryState, []string) {
	var details []string

	magneticodKnown := false
	for _, s := range inv.schemas {
		if s == "magneticod" {
			magneticodKnown = true
			break
		}
	}

	// Fresh: neither our schema nor any magnetico-family table anywhere.
	// Unrelated schemas (e.g. a future users schema) may coexist.
	if !magneticodKnown && len(inv.familyTables) == 0 {
		return stateFresh, nil
	}

	// Legacy markers (checked before anything else, so a legacy database is
	// always refused as legacy — even in a partial state):
	if inv.hasFamilyTableAnywhere("files") {
		for _, qt := range inv.familyTables {
			if strings.HasSuffix(qt, ".files") {
				details = append(details, qt)
			}
		}
	}
	for _, qt := range inv.partitioned {
		details = append(details, qt+" (partitioned)")
	}
	if inv.torrentCols != nil && !containsString(inv.torrentCols, "file_count") {
		details = append(details, "magneticod.torrents without file_count column")
	}
	if len(details) > 0 {
		return stateLegacy, details
	}

	// Unknown objects inside our own schema make the state unverifiable.
	// Every non-sequence relation in magneticod is inventoried, so views,
	// materialized views and foreign tables are caught along with ordinary
	// tables; the details are computed before the missing-objects checks so
	// a degenerate state names everything that was found.
	unknown := unknownObjectDetails(inv)

	// Expected new state: exactly our objects and exactly one version row
	// carrying SchemaVersion.
	wantTables := []string{"torrents", "torrent_file_blobs", "schema_version"}
	var missing []string
	for _, table := range wantTables {
		if !inv.hasFamilyTableAnywhere(table) {
			missing = append(missing, "magneticod."+table)
		}
	}
	for _, index := range expectedIndexes {
		if !containsString(inv.indexes, index) {
			missing = append(missing, "magneticod."+index)
		}
	}
	if len(missing) > 0 {
		return stateUnsupported, append(append(missing, unknown...), detailVersionRows(inv.versionRows))
	}
	if !versionRowsEqual(inv.versionRows, SchemaVersion) {
		return stateUnsupported, append(unknown, detailVersionRows(inv.versionRows))
	}

	for _, index := range inv.indexes {
		if !containsString(expectedIndexes, index) {
			unknown = append(unknown, "unexpected index magneticod."+index)
		}
	}
	if len(unknown) > 0 {
		return stateUnsupported, unknown
	}

	return stateOK, nil
}

// unknownObjectDetails names every inventoried magneticod relation that is
// not one of the expected tables, labeled by relation kind. Sequences are
// never inventoried, so they cannot appear here.
func unknownObjectDetails(inv *catalogInventory) []string {
	known := map[string]bool{"torrents": true, "torrent_file_blobs": true, "schema_version": true}
	var details []string
	for _, obj := range inv.magneticodObjects {
		if known[obj.name] && (obj.kind == "r" || obj.kind == "p") {
			continue
		}
		switch obj.kind {
		case "m":
			details = append(details, "unexpected materialized view magneticod."+obj.name)
		case "v":
			details = append(details, "unexpected view magneticod."+obj.name)
		case "f":
			details = append(details, "unexpected foreign table magneticod."+obj.name)
		default:
			details = append(details, "unexpected table magneticod."+obj.name)
		}
	}
	return details
}

func detailVersionRows(rows []int64) string {
	if rows == nil {
		return "magneticod.schema_version absent"
	}
	if len(rows) == 0 {
		return "magneticod.schema_version is empty"
	}
	parts := make([]string, len(rows))
	for i, v := range rows {
		parts[i] = fmt.Sprintf("version %d", v)
	}
	return "magneticod.schema_version rows: " + strings.Join(parts, ", ")
}

func versionRowsEqual(rows []int64, version int64) bool {
	return len(rows) == 1 && rows[0] == version
}

func containsString(haystack []string, needle string) bool {
	for _, s := range haystack {
		if s == needle {
			return true
		}
	}
	return false
}

// stateError renders a refused state as its typed error.
func stateError(state inventoryState, details []string) error {
	sentinel := ErrUnsupportedSchema
	if state == stateLegacy {
		sentinel = ErrLegacySchema
	}
	if len(details) == 0 {
		return sentinel
	}
	return &SchemaStateError{Err: sentinel, Details: details}
}

// readInventory performs the read-only catalog inventory. It runs BEFORE any
// DDL both in InitSchema (outside the transaction, as the fast path) and
// inside the creation transaction (as the authoritative recheck).
func readInventory(ctx context.Context, q queryer) (*catalogInventory, error) {
	inv := &catalogInventory{}

	rows, err := q.Query(ctx, `SELECT nspname FROM pg_namespace
        WHERE nspname <> 'information_schema' AND nspname NOT LIKE 'pg\_%' ESCAPE '\' ORDER BY 1`)
	if err != nil {
		return nil, err
	}
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			rows.Close()
			return nil, err
		}
		inv.schemas = append(inv.schemas, name)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}

	rows, err = q.Query(ctx, `SELECT n.nspname, c.relname, c.relkind
        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE c.relkind IN ('r','p','v','m','f')
          AND n.nspname <> 'information_schema' AND n.nspname NOT LIKE 'pg\_%' ESCAPE '\'
          AND (n.nspname = 'magneticod'
               OR (c.relkind IN ('r','p')
                   AND c.relname IN ('torrents','files','torrent_file_blobs','schema_version')))
        ORDER BY 1, 2`)
	if err != nil {
		return nil, err
	}
	for rows.Next() {
		var schema, name, kind string
		if err := rows.Scan(&schema, &name, &kind); err != nil {
			rows.Close()
			return nil, err
		}
		qt := schema + "." + name
		if schema == "magneticod" {
			inv.magneticodObjects = append(inv.magneticodObjects, magneticoObject{name: name, kind: kind})
		}
		switch name {
		case "torrents", "files", "torrent_file_blobs", "schema_version":
			// Only real tables reach the family tracking: legacy layouts
			// are tables (plain or partitioned), never views or foreign
			// tables, so a view named "files" cannot fake a legacy marker.
			inv.familyTables = append(inv.familyTables, qt)
			if kind == "p" {
				inv.partitioned = append(inv.partitioned, qt)
			}
		}
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}

	rows, err = q.Query(ctx, `SELECT i.relname FROM pg_index x
        JOIN pg_class i ON i.oid = x.indexrelid
        JOIN pg_class t ON t.oid = x.indrelid
        JOIN pg_namespace n ON n.oid = t.relnamespace
        WHERE n.nspname = 'magneticod'
          AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = i.oid)
        ORDER BY 1`)
	if err != nil {
		return nil, err
	}
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			rows.Close()
			return nil, err
		}
		inv.indexes = append(inv.indexes, name)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}

	rows, err = q.Query(ctx, `SELECT column_name FROM information_schema.columns
        WHERE table_schema = 'magneticod' AND table_name = 'torrents' ORDER BY ordinal_position`)
	if err != nil {
		return nil, err
	}
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			rows.Close()
			return nil, err
		}
		inv.torrentCols = append(inv.torrentCols, name)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}

	if inv.hasFamilyTableAnywhere("schema_version") {
		rows, err = q.Query(ctx, `SELECT version FROM magneticod.schema_version ORDER BY 1`)
		if err != nil {
			return nil, err
		}
		for rows.Next() {
			var version int64
			if err := rows.Scan(&version); err != nil {
				rows.Close()
				return nil, err
			}
			inv.versionRows = append(inv.versionRows, version)
		}
		rows.Close()
		if err := rows.Err(); err != nil {
			return nil, err
		}
	}

	if err := q.QueryRow(ctx,
		`SELECT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm')`).Scan(&inv.trgm); err != nil {
		return nil, err
	}

	return inv, nil
}

// queryer is the subset of pgx.Conn / pgx.Tx used by the inventory.
type queryer interface {
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}

// InitSchema creates the 0.8.0 schema on a fresh database. It is strictly
// non-destructive and concurrency-safe:
//
//  1. A read-only inventory runs BEFORE any DDL. A legacy or partial state is
//     refused with a typed error naming the found objects, and the database
//     is left byte-identical — including when pg_trgm is not yet installed.
//  2. Creation runs in one transaction: pg_advisory_xact_lock, an
//     authoritative in-transaction re-inventory, then CREATE EXTENSION IF NOT
//     EXISTS pg_trgm, the schema objects and the version row. Any failure
//     rolls everything back.
//  3. An already-initialized database takes the idempotent path (exact
//     expected state: version rows == {SchemaVersion}).
func InitSchema(ctx context.Context, rawURL string) error {
	pool, err := connectPool(ctx, rawURL)
	if err != nil {
		return err
	}
	defer pool.Close()

	inv, err := readInventory(ctx, pool)
	if err != nil {
		return fmt.Errorf("%w: %w", ErrStorageIO, err)
	}
	state, details := inv.classify()
	switch state {
	case stateOK:
		return nil
	case stateLegacy, stateUnsupported:
		return stateError(state, details)
	}

	err = pgx.BeginFunc(ctx, pool, func(tx pgx.Tx) error {
		if _, err := tx.Exec(ctx, "SELECT pg_advisory_xact_lock($1)", schemaInitAdvisoryKey); err != nil {
			return err
		}

		// Authoritative recheck inside the transaction: a concurrent
		// initializer may have created the schema after our outer inventory.
		inner, err := readInventory(ctx, tx)
		if err != nil {
			return err
		}
		state, details := inner.classify()
		switch state {
		case stateOK:
			return nil // lost the race: idempotent success
		case stateLegacy, stateUnsupported:
			return stateError(state, details)
		}

		if _, err := tx.Exec(ctx, "CREATE EXTENSION IF NOT EXISTS pg_trgm"); err != nil {
			return fmt.Errorf("installing pg_trgm requires database owner rights: %w", err)
		}
		for _, stmt := range schemaStatements {
			var err error
			if strings.Contains(stmt, "VALUES ($1)") {
				_, err = tx.Exec(ctx, stmt, SchemaVersion)
			} else {
				_, err = tx.Exec(ctx, stmt)
			}
			if err != nil {
				return err
			}
		}
		return nil
	})
	if err != nil {
		var stateErr *SchemaStateError
		if errors.As(err, &stateErr) {
			return stateErr
		}
		return fmt.Errorf("%w: %w", ErrStorageIO, err)
	}
	return nil
}
