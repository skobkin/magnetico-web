func recordsExec(t *testing.T, dsn, sql string) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), pgtest.DBOpTimeout)
	defer cancel()
	conn, err := pgx.Connect(ctx, dsn)
	if err != nil {
		t.Fatalf("fixture connect: %v", err)
	}
	defer conn.Close(context.Background())
	if _, err := conn.Exec(ctx, sql); err != nil {
		t.Fatalf("fixture exec: %v", err)
	}
}

func seedRecordSource(t *testing.T) string {
	t.Helper()
	dsn := pgtest.IntegrationCluster(t).TestDatabase(t)
	recordsExec(t, dsn, recordsSourceDDL)
	return dsn
}

// recordTarget is one seeded target production row.
type recordTarget struct {
	id        int64
	name      string
	totalSize int64
	fileCount int64
	blob      []byte // nil = no blob row
}

// seedRecordsTarget builds a v2 run + production schema; the selected
// record set comes from record-scope error rows for the given IDs.
func seedRecordsTarget(t *testing.T, ids []int64) (*pgxpool.Pool, string) {
	t.Helper()
	ctx := context.Background()
	dsn := pgtest.IntegrationCluster(t).TestDatabase(t)
	pool := forensicsPool(t, dsn)
	runID := seedV2Forensics(t, pool)
	recordsExec(t, dsn, recordsTargetDDL)
	for _, id := range ids {
		if _, err := pool.Exec(ctx, `INSERT INTO magnetico_migration.errors
            (run_id, scope, source_id, stage, category, code)
            VALUES ($1::uuid, 'record', $2, 'validate', 'integrity', 'invalid_metadata')`,
			runID, id); err != nil {
			t.Fatal(err)
		}
	}
	return pool, dsn
}

func seedTargetRecord(t *testing.T, pool *pgxpool.Pool, r recordTarget) {
	t.Helper()
	ctx := context.Background()
	if _, err := pool.Exec(ctx, `INSERT INTO magneticod.torrents
        (id, info_hash, name, total_size, discovered_on, file_count)
        VALUES ($1, decode($2,'hex'), $3, $4, 1700000000, $5)`,
		r.id, fmt.Sprintf("%040x", r.id), r.name, r.totalSize, r.fileCount); err != nil {
		t.Fatal(err)
	}
	if r.blob != nil {
		if _, err := pool.Exec(ctx,
			`INSERT INTO magneticod.torrent_file_blobs (torrent_id, data) VALUES ($1, $2)`,
			r.id, r.blob); err != nil {
			t.Fatal(err)
		}
	}
}

func encodeTestBlob(t *testing.T, files []codec.File) []byte {
	t.Helper()
	enc := codec.NewEncoder(codec.DefaultProfile(), codec.DefaultLimits(), 1)
	blob, _, err := enc.Encode(files)
	if err != nil {
		t.Fatalf("encode fixture blob: %v", err)
	}
	return blob
}

// runRecordsExport runs a records-mode export to a temp path. opts may
// override IncludeBlobs/Limits; IncludeRecords and the source DSN are set
// here.
func runRecordsExport(t *testing.T, targetDSN, sourceDSN string, opts ExportOptions) (string, error) {
	t.Helper()
	if opts.Limits.MaxEvents == 0 {
		opts.Limits = DefaultLimits()
	}
	out := filepath.Join(t.TempDir(), "records.jsonl")
	opts.OutputPath = out
	opts.IncludeRecords = true
	opts.SourceDatabaseURL = sourceDSN
	_, err := ExportErrors(context.Background(), ExportInput{Options: opts, TargetDSN: targetDSN})
	return out, err
}

// recordExpectation describes one record's expected block.
type recordExpectation struct {
	srcStatus    string
	tgtStatus    string
	wantFiles    int    // source_file count
	wantTgtFiles int    // target_file count
	decodeCode   string // "" = no decode_finding expected
	decodeStatus string
	tgtFileCount int64
	assumedPath  string // set when the record's target entry is the assumed single file
	assumedSize  int64
}

// assertRecordBlocks walks the export lines and asserts the per-record
// block contract: metadata events first, then blocks ascending by
// source_id, each block exactly source_record, source_file*,
// target_record?, decode_finding?, target_file*, no blob events without
// --include-blobs, and nothing outside the selected set (the NULL-owner
// orphan file must never be expanded).
func assertRecordBlocks(t *testing.T, lines []map[string]any, want map[int64]recordExpectation) {
	t.Helper()
	phase := 0 // 0 metadata, 1 record blocks, 2 footer
	lastID := int64(0)
	curID := int64(-1)
	var cur recordExpectation
	stage := ""
	sawBlock := map[int64]int{}
	srcFiles := map[int64]int{}
	tgtFiles := map[int64]int{}
	for i, l := range lines {
		typ := str(t, l, "type")
		switch typ {
		case TypeExportHeader, TypeImportRun, TypeImportError, TypeVerificationRun,
			TypeVerificationIssue, TypeRetryRun, TypeRetryAttempt:
			if phase == 1 {
				t.Fatalf("line %d: metadata event %s inside record blocks", i, typ)
			}
			continue
		case TypeExportFooter:
			phase = 2
			continue
		}
		if phase == 2 {
			t.Fatalf("line %d: record event %s after the footer", i, typ)
		}
		phase = 1

		id := intOf(t, l, "source_id")
		if id != curID {
			if typ != TypeSourceRecord {
				t.Fatalf("line %d: record block for %d starts with %s, want source_record", i, id, typ)
			}
			if sawBlock[id] > 0 {
				t.Fatalf("line %d: record %d expanded more than once", i, id)
			}
			if lastID > 0 && id <= lastID {
				t.Fatalf("line %d: source_id %d out of order after %d", i, id, lastID)
			}
			exp, known := want[id]
			if !known {
				t.Fatalf("line %d: unexpected record %d expanded", i, id)
			}
			curID = id
			cur = exp
			stage = "src_record"
			sawBlock[id]++
			lastID = id
			if got := str(t, l, "status"); got != cur.srcStatus {
				t.Fatalf("record %d source status = %s, want %s", id, got, cur.srcStatus)
			}
			continue
		}
		switch typ {
		case TypeSourceRecord:
			t.Fatalf("line %d: duplicate source_record for %d", i, id)
		case TypeSourceFile:
			if !strings.HasPrefix(stage, "src") {
				t.Fatalf("line %d: source_file after stage %q", i, stage)
			}
			stage = "src_file"
			srcFiles[id]++
		case TypeTargetRecord:
			if stage == "" || strings.HasPrefix(stage, "tgt") {
				t.Fatalf("line %d: target_record out of order (stage %q)", i, stage)
			}
			stage = "tgt_record"
			if got := str(t, l, "status"); got != cur.tgtStatus {
				t.Fatalf("record %d target status = %s, want %s", id, got, cur.tgtStatus)
			}
			if cur.tgtStatus == "present" && intOf(t, l, "file_count") != cur.tgtFileCount {
				t.Fatalf("record %d file_count = %v, want %d", id, l["file_count"], cur.tgtFileCount)
			}
		case TypeDecodeFinding:
			if !strings.HasPrefix(stage, "tgt") {
				t.Fatalf("line %d: decode_finding out of order (stage %q)", i, stage)
			}
			stage = "tgt_decode"
			if cur.decodeCode == "" {
				t.Fatalf("record %d: unexpected decode_finding %v", id, l["code"])
			}
			if str(t, l, "code") != cur.decodeCode || str(t, l, "status") != cur.decodeStatus {
				t.Fatalf("record %d decode = %s/%s, want %s/%s",
					id, str(t, l, "status"), str(t, l, "code"), cur.decodeStatus, cur.decodeCode)
			}
		case TypeTargetFile:
			if !strings.HasPrefix(stage, "tgt") {
				t.Fatalf("line %d: target_file out of order (stage %q)", i, stage)
			}
			stage = "tgt_file"
			tgtFiles[id]++
			if cur.assumedPath != "" {
				if fmt.Sprint(l["assumed"]) != "true" {
					t.Fatalf("record %d target_file assumed = %v, want true", id, l["assumed"])
				}
				if str(t, l, "path") != cur.assumedPath || intOf(t, l, "size") != cur.assumedSize {
					t.Fatalf("record %d assumed entry = %v/%v, want %s/%d",
						id, l["path"], l["size"], cur.assumedPath, cur.assumedSize)
				}
			} else if fmt.Sprint(l["assumed"]) == "true" {
				t.Fatalf("record %d: unexpected assumed target_file", id)
			}
		case TypeTargetBlob, TypeTargetBlobChunk:
			t.Fatalf("line %d: blob event without --include-blobs", i)
		default:
			t.Fatalf("line %d: unexpected event %s", i, typ)
		}
	}
	for id, exp := range want {
		if sawBlock[id] != 1 {
			t.Fatalf("record %d appeared %d times, want exactly one block", id, sawBlock[id])
		}
		if srcFiles[id] != exp.wantFiles {
			t.Fatalf("record %d: %d source files, want %d", id, srcFiles[id], exp.wantFiles)
		}
		if tgtFiles[id] != exp.wantTgtFiles {
			t.Fatalf("record %d: %d target files, want %d", id, tgtFiles[id], exp.wantTgtFiles)
		}
	}
}

func TestRecordsExpansionShape(t *testing.T) {
	t.Parallel()
	srcDSN := seedRecordSource(t)

	// Source records: 1 multi-file, 3 with duplicate paths and an empty
	// file, 5 whose target row will be absent. File 90 has a NULL owner —
	// a structural orphan the expansion must never surface.
	recordsExec(t, srcDSN, `INSERT INTO magneticod.torrents (id, info_hash, name, total_size, discovered_on)
        VALUES (1, decode('`+fmt.Sprintf("%040x", 1)+`','hex'), 'multi', 300, 1700000001),
               (3, decode('`+fmt.Sprintf("%040x", 3)+`','hex'), 'dups', 30, 1700000003),
               (5, decode('`+fmt.Sprintf("%040x", 5)+`','hex'), 'gone-target', 50, 1700000005)`)
	recordsExec(t, srcDSN, `INSERT INTO magneticod.files (id, torrent_id, size, path)
        VALUES (11, 1, 100, 'a.bin'), (12, 1, 200, 'b/c.bin'),
               (13, 3, 10, 'dup.bin'), (14, 3, 20, 'dup.bin'),
               (15, 3, 0, 'empty.bin'),
               (90, NULL, 5, 'orphan.bin')`)

	pool, dsn := seedRecordsTarget(t, []int64{1, 2, 3, 4, 5, 6})

	// Target records: 1 = decoded multi-file blob; 2 = absent source,
	// file_count=1, no blob (assumed single); 5 = file_count=3, no blob
	// (missing_blob); 3 and 4 = source-side only; 6 = absent on both sides.
	seedTargetRecord(t, pool, recordTarget{id: 1, name: "multi", totalSize: 300, fileCount: 2,
		blob: encodeTestBlob(t, []codec.File{{Path: "a.bin", Size: 100}, {Path: "b/c.bin", Size: 200}})})
	seedTargetRecord(t, pool, recordTarget{id: 2, name: "solo", totalSize: 42, fileCount: 1})
	seedTargetRecord(t, pool, recordTarget{id: 5, name: "missing", totalSize: 50, fileCount: 3})

	out, err := runRecordsExport(t, dsn, srcDSN, ExportOptions{})
	if err != nil {
		t.Fatalf("ExportErrors(records) error = %v", err)
	}
	lines := jsonLines(t, out)
	assertRecordBlocks(t, lines, map[int64]recordExpectation{
		1: {srcStatus: "present", tgtStatus: "present", wantFiles: 2, wantTgtFiles: 2,
			decodeCode: "decoded", decodeStatus: "decoded", tgtFileCount: 2},
		2: {srcStatus: "absent", tgtStatus: "present", wantFiles: 0, wantTgtFiles: 1,
			decodeCode: "assumed_single", decodeStatus: "not_attempted",
			tgtFileCount: 1, assumedPath: "solo", assumedSize: 42},
		3: {srcStatus: "present", tgtStatus: "absent", wantFiles: 3},
		4: {srcStatus: "absent", tgtStatus: "absent", wantFiles: 0},
		5: {srcStatus: "present", tgtStatus: "present", wantFiles: 0,
			decodeCode: "missing_blob", decodeStatus: "failed", tgtFileCount: 3},
		6: {srcStatus: "absent", tgtStatus: "absent", wantFiles: 0},
	})

	// Decoded entries preserve the blob's exact file list (path + size, in
	// decoded order).
	var gotFiles int
	for _, l := range lines {
		if str(t, l, "type") != TypeTargetFile || intOf(t, l, "source_id") != 1 {
			continue
		}
		path, size := str(t, l, "path"), intOf(t, l, "size")
		switch gotFiles {
		case 0:
			if path != "a.bin" || size != 100 {
				t.Fatalf("first decoded file = %s/%d, want a.bin/100", path, size)
			}
		case 1:
			if path != "b/c.bin" || size != 200 {
				t.Fatalf("second decoded file = %s/%d, want b/c.bin/200", path, size)
			}
		}
		gotFiles++
	}
	if gotFiles != 2 {
		t.Fatalf("record 1 target files = %d, want 2", gotFiles)
	}

	// Duplicate source paths are preserved with their own file IDs (and the
	// empty file survives — no codec retention applies).
	var dupPaths []string
	for _, l := range lines {
		if str(t, l, "type") == TypeSourceFile && intOf(t, l, "source_id") == 3 {
			dupPaths = append(dupPaths, fmt.Sprintf("%v:%s", l["file_id"], str(t, l, "path")))
		}
	}
	if len(dupPaths) != 3 ||
		dupPaths[0] != "13:dup.bin" || dupPaths[1] != "14:dup.bin" || dupPaths[2] != "15:empty.bin" {
		t.Fatalf("source files of record 3 = %v, want duplicates + empty preserved with file IDs", dupPaths)
	}
}

func TestRecordsBlobRoundTripEvenWhenDecodeFails(t *testing.T) {
	t.Parallel()
	srcDSN := seedRecordSource(t)
	recordsExec(t, srcDSN, `INSERT INTO magneticod.torrents (id, info_hash, name, total_size, discovered_on)
        VALUES (1, decode('`+fmt.Sprintf("%040x", 1)+`','hex'), 'corrupt', 9, 1700000001)`)

	pool, dsn := seedRecordsTarget(t, []int64{1})
	// A stored blob whose bytes decode-fail (an invalid envelope).
	corrupt := append([]byte{0x78, 0xda}, []byte("this is not a valid codec stream at all")...)
	seedTargetRecord(t, pool, recordTarget{id: 1, name: "corrupt", totalSize: 9, fileCount: 1, blob: corrupt})

	out, err := runRecordsExport(t, dsn, srcDSN, ExportOptions{IncludeBlobs: true})
	if err != nil {
		t.Fatalf("ExportErrors error = %v", err)
	}
	lines := jsonLines(t, out)

	var blob map[string]any
	var chunks []map[string]any
	decodeFailed := false
	for _, l := range lines {
		switch str(t, l, "type") {
		case TypeTargetBlob:
			blob = l
		case TypeTargetBlobChunk:
			chunks = append(chunks, l)
		case TypeDecodeFinding:
			decodeFailed = str(t, l, "status") == "failed"
		}
	}
	if blob == nil || len(chunks) == 0 {
		t.Fatalf("blob=%v chunks=%d — a failed decode must never suppress the raw export", blob, len(chunks))
	}
	if !decodeFailed {
		t.Fatal("corrupt blob did not produce a failed decode finding")
	}
	// Exact lossless round-trip: concat(base64-decode of chunks by ascending
	// chunk_index) == the stored bytes.
	var rebuilt []byte
	for i, c := range chunks {
		if intOf(t, c, "chunk_index") != int64(i) {
			t.Fatalf("chunk %d has index %v", i, c["chunk_index"])
		}
		raw, derr := base64.StdEncoding.DecodeString(str(t, c, "data_base64"))
		if derr != nil {
			t.Fatalf("chunk %d base64: %v", i, derr)
		}
		if int64(len(raw)) != intOf(t, c, "chunk_bytes") {
			t.Fatalf("chunk %d length mismatch: %d vs %v", i, len(raw), c["chunk_bytes"])
		}
		rebuilt = append(rebuilt, raw...)
	}
	if string(rebuilt) != string(corrupt) {
		t.Fatalf("round-trip mismatch: %d bytes rebuilt, want %d", len(rebuilt), len(corrupt))
	}
	sum := sha256.Sum256(corrupt)
	if str(t, blob, "sha256") != hex.EncodeToString(sum[:]) {
		t.Fatalf("blob sha256 = %v, want %x", blob["sha256"], sum)
	}
	if intOf(t, blob, "stored_bytes") != int64(len(corrupt)) {
		t.Fatalf("stored_bytes = %v, want %d", blob["stored_bytes"], len(corrupt))
	}
}

func TestRecordsOverLimitBlobExportsRaw(t *testing.T) {
	t.Parallel()
	srcDSN := seedRecordSource(t)
	recordsExec(t, srcDSN, `INSERT INTO magneticod.torrents (id, info_hash, name, total_size, discovered_on)
        VALUES (1, decode('`+fmt.Sprintf("%040x", 1)+`','hex'), 'huge', 9, 1700000001)`)

	pool, dsn := seedRecordsTarget(t, []int64{1})
	// One byte past the codec stored limit; the content is not a valid
	// envelope — and it is NEVER fed to codec.Decode (a decode attempt
	// would report a framing/wire finding, not blob_over_limit).
	size := int64(codec.DefaultLimits().MaxStoredBytes) + 1
	oversized := make([]byte, size)
	for i := range oversized {
		oversized[i] = byte(i % 251)
	}
	seedTargetRecord(t, pool, recordTarget{id: 1, name: "huge", totalSize: 9, fileCount: 2, blob: oversized})

	out, err := runRecordsExport(t, dsn, srcDSN, ExportOptions{IncludeBlobs: true})
	if err != nil {
		t.Fatalf("ExportErrors error = %v", err)
	}
	lines := jsonLines(t, out)

	var foundOverLimit, foundBlob bool
	var rebuilt []byte
	chunkCount := 0
	for _, l := range lines {
		switch str(t, l, "type") {
		case TypeDecodeFinding:
			if str(t, l, "code") == "blob_over_limit" {
				foundOverLimit = true
				if str(t, l, "status") != "not_attempted" {
					t.Fatalf("over-limit decode status = %v, want not_attempted", l["status"])
				}
				details := l["details"].(map[string]any)
				if fmt.Sprint(details["limit"]) != "stored_bytes" {
					t.Fatalf("blob_over_limit details = %v", details)
				}
			}
		case TypeTargetBlob:
			foundBlob = true
			if intOf(t, l, "stored_bytes") != size {
				t.Fatalf("stored_bytes = %v, want %d", l["stored_bytes"], size)
			}
		case TypeTargetBlobChunk:
			raw, derr := base64.StdEncoding.DecodeString(str(t, l, "data_base64"))
			if derr != nil {
				t.Fatalf("chunk base64: %v", derr)
			}
			rebuilt = append(rebuilt, raw...)
			chunkCount++
		case TypeTargetFile:
			t.Fatal("over-limit blob produced target_file events — it must not decode")
		}
	}
	if !foundOverLimit || !foundBlob {
		t.Fatalf("over-limit=%v blob=%v — BOTH are required (finding 5: decode and raw export are independent)", foundOverLimit, foundBlob)
	}
	if len(rebuilt) != int(size) {
		t.Fatalf("raw round-trip = %d bytes, want %d", len(rebuilt), size)
	}
	for i, b := range rebuilt {
		if b != byte(i%251) {
			t.Fatalf("round-trip corrupted at byte %d", i)
		}
	}
	if chunkCount < int(size/blobChunkBytes) {
		t.Fatalf("chunk count %d too low for %d bytes", chunkCount, size)
	}
}

func TestRecordsBlobOverCapIsHardError(t *testing.T) {
	t.Parallel()
	srcDSN := seedRecordSource(t)
	recordsExec(t, srcDSN, `INSERT INTO magneticod.torrents (id, info_hash, name, total_size, discovered_on)
        VALUES (1, decode('`+fmt.Sprintf("%040x", 1)+`','hex'), 'big', 9, 1700000001)`)

	pool, dsn := seedRecordsTarget(t, []int64{1})
	// 3 MiB stored: within the codec limit (so the decode decision still
	// runs) but over the 1 MiB forensic cap (so the raw-export decision
	// hard-fails the export — never skip, never truncate).
	size := int64(3 << 20)
	seedTargetRecord(t, pool, recordTarget{id: 1, name: "big", totalSize: 9, fileCount: 1,
		blob: make([]byte, size)})

	limits := DefaultLimits()
	limits.MaxBlobBytes = 1 << 20
	out, err := runRecordsExport(t, dsn, srcDSN, ExportOptions{IncludeBlobs: true, Limits: limits})
	if !errors.Is(err, ErrExportCapExceeded) || !strings.Contains(err.Error(), "--max-blob-bytes") {
		t.Fatalf("error = %v, want the max-blob-bytes hard error naming the flag", err)
	}
	if !strings.Contains(err.Error(), fmt.Sprintf("%d", size)) {
		t.Fatalf("error does not name the blob size: %v", err)
	}
	assertNoOutput(t, filepath.Dir(out), filepath.Base(out))
}

func TestRecordsTypedRefusals(t *testing.T) {
	t.Parallel()
	ctx := context.Background()

	t.Run("records need a source DSN", func(t *testing.T) {
		t.Parallel()
		// Validation refuses before any connection is attempted.
		_, err := ExportErrors(ctx, ExportInput{
			Options: ExportOptions{
				OutputPath:     filepath.Join(t.TempDir(), "x.jsonl"),
				IncludeRecords: true,
				Limits:         DefaultLimits(),
			},
			TargetDSN: "postgres://127.0.0.1:1/none",
		})
		if !errors.Is(err, ErrRecordsRequireSource) {
			t.Fatalf("error = %v, want ErrRecordsRequireSource", err)
		}
	})

	t.Run("unavailable source fails records but not metadata", func(t *testing.T) {
		t.Parallel()
		_, dsn := seedRecordsTarget(t, []int64{7})
		bogus := "postgres://127.0.0.1:1/absent"
		out, err := runRecordsExport(t, dsn, bogus, ExportOptions{})
		if !errors.Is(err, ErrSourceUnavailable) {
			t.Fatalf("error = %v, want ErrSourceUnavailable", err)
		}
		assertNoOutput(t, filepath.Dir(out), filepath.Base(out))

		// The SAME target exports metadata-only fine (source never contacted).
		ok, err := ExportErrors(ctx, ExportInput{
			Options:   ExportOptions{OutputPath: filepath.Join(t.TempDir(), "meta.jsonl"), Limits: DefaultLimits()},
			TargetDSN: dsn,
		})
		if err != nil {
			t.Fatalf("metadata-only export error = %v", err)
		}
		if ok.Events == 0 {
			t.Fatal("metadata export empty")
		}
	})

	t.Run("same database refused", func(t *testing.T) {
		t.Parallel()
		// Source schema AND migration registry on one database: the records
		// pass must refuse to use its own target as the source.
		dsn := pgtest.IntegrationCluster(t).TestDatabase(t)
		recordsExec(t, dsn, recordsSourceDDL)
		seedV2Forensics(t, forensicsPool(t, dsn))
		_, err := runRecordsExport(t, dsn, dsn, ExportOptions{})
		if !errors.Is(err, target.ErrSameDatabase) {
			t.Fatalf("error = %v, want target.ErrSameDatabase", err)
		}
	})

	t.Run("missing target production schema refused", func(t *testing.T) {
		t.Parallel()
		// A migration registry WITHOUT magneticod: a fresh v2 target.
		dsn := pgtest.IntegrationCluster(t).TestDatabase(t)
		seedV2Forensics(t, forensicsPool(t, dsn))
		srcDSN := seedRecordSource(t)
		_, err := runRecordsExport(t, dsn, srcDSN, ExportOptions{})
		if !errors.Is(err, ErrRecordsTargetUnavailable) {
			t.Fatalf("error = %v, want ErrRecordsTargetUnavailable", err)
		}
	})
}

func TestRecordsMaxRecordsCap(t *testing.T) {
	t.Parallel()
	srcDSN := seedRecordSource(t)
	recordsExec(t, srcDSN, `INSERT INTO magneticod.torrents (id, info_hash, name, total_size, discovered_on)
        VALUES (1, decode('`+fmt.Sprintf("%040x", 1)+`','hex'), 'one', 1, 1700000001),
               (2, decode('`+fmt.Sprintf("%040x", 2)+`','hex'), 'two', 2, 1700000002),
               (3, decode('`+fmt.Sprintf("%040x", 3)+`','hex'), 'three', 3, 1700000003)`)

	_, dsn := seedRecordsTarget(t, []int64{1, 2, 3})
	limits := DefaultLimits()
	limits.MaxRecords = 2
	out, err := runRecordsExport(t, dsn, srcDSN, ExportOptions{Limits: limits})
	if !errors.Is(err, ErrExportCapExceeded) || !strings.Contains(err.Error(), "max-records") {
		t.Fatalf("error = %v, want the max-records cap", err)
	}
	assertNoOutput(t, filepath.Dir(out), filepath.Base(out))
}
